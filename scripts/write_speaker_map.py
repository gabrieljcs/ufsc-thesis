"""Generate the language-community map with country boundaries and a Europe inset."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'eval/data/cartography'
COUNTRIES = json.loads((DATA / 'ne_110m_admin_0_countries.geojson').read_text())
COMMUNITIES = json.loads((DATA / 'reference_communities.json').read_text())
RADIUS = {'tiny': 2.2, 'small': 3.0, 'medium': 4.0, 'large': 5.1, 'huge': 6.3}
LANGUAGES = {
    'English': ('3979A8', 'huge'), 'Spanish': ('C65A35', 'huge'),
    'Portuguese': ('8060A6', 'large'), 'Arabic': ('C59A31', 'large'),
    'Swahili': ('398A6E', 'medium'), 'Russian': ('AE5266', 'large'),
    'Italian': ('BB8A5B', 'medium'), 'Norwegian': ('54879B', 'tiny'),
    'Swedish': ('4F6C86', 'small'), 'Danish': ('397C82', 'tiny'),
    'Finnish': ('748C42', 'tiny'), 'Ukrainian': ('9A7090', 'small'),
    'Bulgarian': ('A5714F', 'tiny'),
}
WORLD = (-170, 180, -55, 80)
EUROPE = (-15, 43, 34, 73)

def xy(lon, lat, bounds, box):
    lo, hi, bot, top = bounds
    x, y, w, h = box
    return x + (lon-lo)/(hi-lo)*w, y + (lat-bot)/(top-bot)*h

def basemap(bounds, box):
    x, y, w, h = box
    out = [rf'\begin{{scope}}\clip ({x},{y}) rectangle ({x+w},{y+h});',
           rf'\fill[MapOcean] ({x},{y}) rectangle ({x+w},{y+h});']
    for feature in COUNTRIES['features']:
        g = feature['geometry']
        polygons = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for polygon in polygons:
            coords = ' -- '.join('({:.3f},{:.3f})'.format(*xy(lon,lat,bounds,box)) for lon,lat,*_ in polygon[0])
            out.append(r'\path[fill=MapLand,draw=MapBorder,line width=0.18pt] '+coords+r' -- cycle;')
    out += [r'\end{scope}',rf'\draw[black!15,line width=0.3pt] ({x},{y}) rectangle ({x+w},{y+h});']
    return out

def marker(language, lon, lat, bounds, box):
    x, y = xy(lon, lat, bounds, box)
    _, size = LANGUAGES[language]
    return rf'\path[fill=Map{language},fill opacity=0.88,draw=white,line width=0.6pt] ({x:.3f},{y:.3f}) circle ({RADIUS[size]}pt);'

def label(language, lon, lat, bounds, box, dx, dy, anchor='center'):
    x, y = xy(lon, lat, bounds, box)
    return [rf'\draw[black!40,line width=0.3pt] ({x:.3f},{y:.3f}) -- ({x+dx:.3f},{y+dy:.3f});',
            rf'\node[font=\scriptsize,anchor={anchor},fill=white,fill opacity=0.92,text opacity=1,inner sep=1.4pt] at ({x+dx:.3f},{y+dy:.3f}) {{{language}}};']

world_box = (0,5.4,13.5,5.5)
europe_box = (0,0,8,4.65)
lines = [r'% Generated by eval/scripts/write_speaker_map.py',
         r'\definecolor{MapOcean}{HTML}{F5F8FA}',
         r'\definecolor{MapLand}{HTML}{E5E9EB}',
         r'\definecolor{MapBorder}{HTML}{CBD2D6}']
lines += [rf'\definecolor{{Map{name}}}{{HTML}}{{{color}}}' for name,(color,_) in LANGUAGES.items()]
lines += [r'\begin{tikzpicture}[x=1cm,y=1cm]',
          r'\node[anchor=west,font=\small\bfseries] at (0,11.25) {A\quad Global speaker communities};']
lines += basemap(WORLD,world_box)
for language, locations in COMMUNITIES.items():
    for lon, lat in locations:
        if not (EUROPE[0] <= lon <= EUROPE[1] and EUROPE[2] <= lat <= EUROPE[3]):
            lines.append(marker(language,lon,lat,WORLD,world_box))
for language,lon,lat,dx,dy in [
    ('English',-100,39,-.55,.5),('Spanish',-99,19,-.6,-.42),
    ('Portuguese',-47,-15,1,-.28),('Arabic',39,24,.55,.62),
    ('Swahili',37,-6,.85,-.5),('Russian',70,56,.8,.5)]:
    lines += label(language,lon,lat,WORLD,world_box,dx,dy)
a,b=xy(EUROPE[0],EUROPE[2],WORLD,world_box); c,d=xy(EUROPE[1],EUROPE[3],WORLD,world_box)
lines += [rf'\draw[black!40,dashed,line width=0.4pt] ({a:.3f},{b:.3f}) rectangle ({c:.3f},{d:.3f});',
          r'\node[anchor=west,font=\small\bfseries] at (0,5.02) {B\quad European detail};']
lines += basemap(EUROPE,europe_box)
for language, locations in COMMUNITIES.items():
    for lon,lat in locations:
        if EUROPE[0] <= lon <= EUROPE[1] and EUROPE[2] <= lat <= EUROPE[3]:
            lines.append(marker(language,lon,lat,EUROPE,europe_box))
for language,dx,dy in [
    ('English',-.65,.15),('Spanish',.5,-.38),('Portuguese',-.25,.48),
    ('Italian',-.65,-.22),('Norwegian',-.65,.48),('Swedish',.75,-.05),
    ('Danish',.55,-.3),('Finnish',.6,.35),('Ukrainian',.5,.35),('Bulgarian',.6,-.3)]:
    lon,lat=next((lon,lat) for lon,lat in COMMUNITIES[language] if EUROPE[0] <= lon <= EUROPE[1] and EUROPE[2] <= lat <= EUROPE[3])
    lines += label(language,lon,lat,EUROPE,europe_box,dx,dy)
lines += [r'\node[anchor=west,font=\small\bfseries] at (8.65,4.1) {Total speakers};',
          r'\node[anchor=west,font=\scriptsize,text=black!60] at (8.65,3.67) {Marker size by population bin};']
for i,(text,size) in enumerate([('$<10$ million','tiny'),('10--50 million','small'),('50--250 million','medium'),('250--500 million','large'),('$>500$ million','huge')]):
    y=3.08-i*.6
    lines += [rf'\path[fill=black!55,draw=white,line width=0.5pt] (8.9,{y}) circle ({RADIUS[size]}pt);',
              rf'\node[anchor=west,font=\scriptsize] at (9.3,{y}) {{{text}}};']
lines += [r'\node[anchor=west,font=\scriptsize,text=black!60] at (8.65,-0.03) {Color identifies the language.};',r'\end{tikzpicture}']
(ROOT/'ufscthesisx/ufscthesisx/figures/attack_language_map.tex').write_text('\n'.join(lines)+'\n')
