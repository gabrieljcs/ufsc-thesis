"""Post-review descriptive reference correlations from saved language-cell means."""
import csv
import hashlib
import json
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'eval/outputs/releases/2026-09-29-graded-reporting/cell_summary.csv'
RELEASE=ROOT/'eval/outputs/releases/2026-10-11-reference-descriptive-contrast'
OUT=ROOT/'ufscthesisx/ufscthesisx/chapters/reference_descriptive_contrast.tex'
rows=[r for r in csv.DictReader(SOURCE.open()) if r['model']=='llama3_1_8b_reference']
assert len(rows)==13 and len({r['attack_language'] for r in rows})==13

def rank(values):
    return [sum(x<v for x in values)+(sum(x==v for x in values)+1)/2 for v in values]

def spearman(x,y):
    a,b=rank(x),rank(y)
    am,bm=sum(a)/len(a),sum(b)/len(b)
    return sum((u-am)*(v-bm) for u,v in zip(a,b))/(sum((u-am)**2 for u in a)*sum((v-bm)**2 for v in b))**.5

export=[]
for scope,group in [('all_languages',rows),('non_aligned',[r for r in rows if r['attack_language']!='eng'])]:
    for predictor in ['distance','spec_score']:
        export.append(dict(scope=scope,predictor=predictor,n_languages=len(group),spearman_rho=spearman([float(r[predictor]) for r in group],[float(r['mean_score']) for r in group])))
lookup={(r['scope'],r['predictor']):r['spearman_rho'] for r in export}
english=next(r for r in rows if r['attack_language']=='eng')
swahili=next(r for r in rows if r['attack_language']=='swa')
text=(
    r'An additional post-review descriptive check examines the English reference separately (Figures~\ref{fig:strongreject-profiles}--\ref{fig:belebele-profiles}). '
    'Across its thirteen observed language cells, the Spearman correlation between distance and mean StrongREJECT score is '
    +rf"$\rho={lookup['all_languages','distance']:.2f}$, while the correlation with SPEC is $\rho={lookup['all_languages','spec_score']:.2f}$. "
    'English has the lowest mean score ('+f"{float(english['mean_score']):.3f}"+'), whereas Swahili, the most distant language and the cell with the lowest SPEC, has the highest ('+f"{float(swahili['mean_score']):.3f}"+'). '
    'When English is excluded, the distance correlation falls to '
    +rf"$\rho={lookup['non_aligned','distance']:.2f}$ and the SPEC correlation remains negative at $\rho={lookup['non_aligned','spec_score']:.2f}$. "
    'Thus, the reference descriptively follows the negative specialization direction expected by H\\textsubscript{2} more clearly than the positive distance direction expected by H\\textsubscript{1}. '
    'These are unadjusted correlations over a purposive language inventory, calculated after inspecting the reference profiles; they have no inferential intervals here and do not assess H\\textsubscript{3}. '
    'The reference remains excluded from paired inference, and its pattern does not change the paired-panel hypothesis conclusions.\n'
)
OUT.write_text('% Generated by eval/scripts/write_reference_descriptive_contrast.py.\n'+text)
RELEASE.mkdir(exist_ok=True)
with (RELEASE/'correlations.csv').open('w',newline='') as handle:
    writer=csv.DictWriter(handle,fieldnames=list(export[0]));writer.writeheader();writer.writerows(export)
for p in [OUT,Path(__file__)]:shutil.copy2(p,RELEASE/p.name)
(RELEASE/'manifest.json').write_text(json.dumps({'role':'Post-review descriptive contrast; no paired regression changes.','source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'source':str(SOURCE.relative_to(ROOT)),'code_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),'unit':'Observed model-language mean','scopes':['13 languages','12 non-aligned languages'],'uncertainty':'No inferential intervals or p-values claimed.'},indent=2)+'\n')
