"""Generate the paired graded-distance figure from the released cell summary.

The existing graded reporting release is read-only. This presentation update
gets its own provenance directory and writes a PGFPlots figure for the thesis.
"""

import csv
import hashlib
import json
from pathlib import Path
import shutil


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "eval/outputs/releases/2026-09-29-graded-reporting/cell_summary.csv"
RELEASE = ROOT / "eval/outputs/releases/2026-09-30-paired-graded-distance-figure"
FIGURE = ROOT / "ufscthesisx/ufscthesisx/figures/graded_distance_pairs.tex"

PAIRS = (
    ("Portuguese", ("sagui_7b", "Sagui-7B"), ("sabia_3", "Sabi\\'a-3")),
    ("Italian", ("llamantino_2_ultrachat_7b", "LLaMAntino-2"),
     ("llamantino_anita_8b", "ANITA-8B")),
    ("Swedish", ("gpt_sw3", "GPT-SW3"),
     ("ai_sweden_llama3_8b", "AI Sweden")),
    ("Bulgarian", ("bggpt_7b", "BgGPT-7B"),
     ("bggpt_gemma_9b", "BgGPT-Gemma")),
)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


rows = list(csv.DictReader(SOURCE.open(newline="", encoding="utf-8")))
by_model = {}
for row in rows:
    by_model.setdefault(row["model"], []).append(row)

lines = [
    "% Generated by eval/scripts/write_paired_graded_distance_tex.py.",
    "% Source SHA-256: " + sha256(SOURCE),
    r"\definecolor{gradedweakblue}{RGB}{35,103,159}",
    r"\definecolor{gradedstrongorange}{RGB}{202,86,42}",
    r"\begin{tikzpicture}",
    r"\begin{groupplot}[",
    r"  group style={group size=2 by 2,horizontal sep=1.7cm,vertical sep=2.05cm},",
    r"  width=7.05cm,height=5.8cm,",
    r"  xmin=-0.015,xmax=0.63,ymin=0,ymax=1,",
    r"  xtick={0,0.2,0.4,0.6},ytick={0,0.2,0.4,0.6,0.8,1},",
    r"  xlabel={URIEL+ distance},ylabel={Mean official score},",
    r"  grid=major,grid style={black!12},",
    r"  tick label style={font=\scriptsize},label style={font=\footnotesize},",
    r"  title style={font=\bfseries\small},",
    r"  legend style={at={(0.02,0.98)},anchor=north west,font=\scriptsize,",
    r"    draw=black!20,fill=white,fill opacity=.88,text opacity=1},",
    r"  legend cell align=left",
    r"]",
]

for pair_name, weak, strong in PAIRS:
    model_rows = []
    for model_id, _ in (weak, strong):
        model = by_model.get(model_id, [])
        if len(model) != 13 or len({r["attack_language"] for r in model}) != 13:
            raise ValueError(f"Expected 13 unique language cells for {model_id}")
        for row in model:
            distance, score = float(row["distance"]), float(row["mean_score"])
            if not (0 <= distance <= 1 and 0 <= score <= 1):
                raise ValueError(f"Out-of-range value for {model_id}: {row}")
        model_rows.append(sorted(model, key=lambda r: (float(r["distance"]), r["attack_language"])))
    weak_dist = {r["attack_language"]: float(r["distance"]) for r in model_rows[0]}
    strong_dist = {r["attack_language"]: float(r["distance"]) for r in model_rows[1]}
    if any(abs(weak_dist[lang] - strong_dist[lang]) > 1e-9 for lang in weak_dist):
        raise ValueError(f"Pair distance mismatch: {pair_name}")

    lines.append(r"\nextgroupplot[title={" + pair_name + "}]")
    for (model_id, label), data, color in zip(
        (weak, strong), model_rows, ("gradedweakblue", "gradedstrongorange")
    ):
        lines.append(
            r"\addplot+[color=" + color
            + r",line width=.75pt,mark=*,mark size=1.5pt] coordinates {"
        )
        for row in data:
            distance = float(row["distance"])
            score = float(row["mean_score"])
            lines.append(f"  ({distance:.5f},{score:.6f}) % {row['attack_language']}")
        lines.append("};")
        lines.append(r"\addlegendentry{" + label + "}")

lines += [r"\end{groupplot}", r"\end{tikzpicture}", ""]
figure_text = "\n".join(lines)
FIGURE.parent.mkdir(parents=True, exist_ok=True)
FIGURE.write_text(figure_text, encoding="utf-8")

RELEASE.mkdir(parents=True, exist_ok=True)
(RELEASE / "code").mkdir(exist_ok=True)
release_figure = RELEASE / FIGURE.name
release_figure.write_text(figure_text, encoding="utf-8")
release_code = RELEASE / "code" / Path(__file__).name
shutil.copy2(__file__, release_code)
manifest = {
    "purpose": "Paired descriptive distance figure for the graded StrongREJECT manuscript",
    "source": str(SOURCE.relative_to(ROOT)),
    "source_sha256": sha256(SOURCE),
    "figure": str(FIGURE.relative_to(ROOT)),
    "figure_sha256": sha256(FIGURE),
    "generator": str(Path(__file__).relative_to(ROOT)),
    "generator_sha256": sha256(release_code),
    "paired_models": [name for name, _, _ in PAIRS],
    "outcome": "mean official StrongREJECT score over scored responses, zeros included",
    "line_interpretation": "descriptive connections ordered by URIEL+ distance; no fitted trend",
}
(RELEASE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
print(FIGURE)
