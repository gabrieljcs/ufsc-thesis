"""Generate corrected numerical thesis tables/text from the versioned release."""
from pathlib import Path
import pandas as pd

ROOT=Path(__file__).resolve().parents[2]
T=ROOT/'eval/outputs/releases/2026-09-09-corrected/tables'
OUT=ROOT/'ufscthesisx/ufscthesisx/chapters/quality_corrected_assets.tex'
PARTS=['% Generated by eval/scripts/write_quality_latex_assets.py; do not hand-edit values.']
NAMES={'sagui_7b':'Sagui-7B','sabia_3':r"Sabi\'a-3",'llamantino_2_ultrachat_7b':'LLaMAntino-2',
       'llamantino_anita_8b':'ANITA','gpt_sw3':'GPT-SW3','ai_sweden_llama3_8b':'AI Sweden',
       'bggpt_7b':'BgGPT-7B','bggpt_gemma_9b':'BgGPT-Gemma','llama3_1_8b_reference':'English reference'}
PRED={'distance_z':'Distance','spec_z':'SPEC','if_z':'IF','cons_z':'CONS','token_inflation_z':'Token inflation'}
FITS={'pooled':'Pooled','weak':'Weak','strong':'Strong','spec_components':'IF/CONS',
      'tokenizer_robustness':'Tokenizer','excluding_aligned_language':'Excludes aligned language',
      'excluding_translation_caveat_languages':'Excludes fin/swa/ukr','excluding_blaser_flagged':'Excludes BLASER flags',
      'original_complete_cell_cohort':'Excludes weak Italian/rus','cons_at_least_100_comparisons':r'CONS comparisons $\geq100$',
      'excluding_two_questionable_gold_items':'Excludes two questionable items','main_on_tokenizer_cohort':'Main on tokenizer cohort'}


def read(name):return pd.read_csv(T/name)
def f(value):return f'{value:.3f}'
def integer(value):return f'{int(value):,}'.replace(',',r'\,')
def interval(r):return f"{r.odds_ratio:.3f} [{r.odds_ratio_ci_lower:.3f}, {r.odds_ratio_ci_upper:.3f}]"
def macro(name,value):PARTS.append('\\newcommand{\\'+name+'}{'+str(value)+'}')


def table(name,label,caption,headers,rows,columns=None,note='',source=r'Prepared by the author (2026), based on the versioned analysis supplement (Section~\ref{sec:code-data-availability}).'):
    columns=columns or 'X'+'r'*(len(headers)-1)
    body=['\\begin{table}[H]',r'\centering\small',r'\setlength{\tabcolsep}{4pt}',
          '\\begin{tabularx}{\\linewidth}{'+columns+'}',
          '\\caption{'+caption+'}','\\label{'+label+'}'+r' \\',r'\toprule',
          ' & '.join(headers)+r' \\',r'\midrule']
    body+=[' & '.join(map(str,row))+r' \\' for row in rows]
    body += [r'\bottomrule',r'\end{tabularx}']
    if label == 'tab:translation-robustness':
        body[5] = body[5].replace(r' \\', r'\label{tab:external-validation} \\')
    if note:body += [r'\par\smallskip{\footnotesize '+note+'}']
    body += [r'\fonte{'+source+'}',r'\end{table}']
    macro(name,'\n'+'\n'.join(body)+'\n')


def effects(name,label,caption,filename,strata=False):
    data=read(filename);rows=[]
    for r in data.itertuples():
        title=(FITS.get(r.fit,r.fit)+': ' if strata else '')+PRED[r.predictor]
        rows.append([title,f(r.estimate),f(r.std_error),interval(r),integer(r.n)])
    table(name,label,caption,['Standardized predictor',r'$\beta$','SE',r'OR [95\% interval]',r'$n$'],rows,
          note='Laplace approximate credible intervals unless the caption specifies robust GEE confidence intervals.')


def main():
    main=read('glmm_main_effects.csv').set_index('predictor')
    macro('QMainN',integer(main.loc['distance_z','n']))
    macro('QDistanceOR',interval(main.loc['distance_z']))
    macro('QSpecOR',interval(main.loc['spec_z']))
    corr=read('spec_asr_correlation.csv').set_index('model')
    table('QualitySpecCorrelationTable','tab:spec-asr-correlation','Specialization--ASR correlations',
          ['Model','Languages',r'$\rho$',r'95\% bootstrap interval'],
          [[name,int(corr.loc[m,'n']),f(corr.loc[m,'spearman_rho']),f"[{corr.loc[m,'ci_low']:.3f}, {corr.loc[m,'ci_high']:.3f}]"] for m,name in NAMES.items()],
          note='Descriptive intervals over the purposive language inventory; not population-level language inference.')
    for args in [
        ('QualityMainTable','tab:glmm-main-effects','Crossed-effects Laplace/MAP model','glmm_main_effects.csv'),
        ('QualityTokenizerTable','tab:glmm-tokenizer-robustness','Tokenizer robustness model','glmm_tokenizer_robustness.csv'),
        ('QualityComponentsTable','tab:glmm-spec-components','IF/CONS decomposition','glmm_spec_components.csv'),
        ('QualityGeeTable','tab:glmm-gee-sensitivity','Prompt-clustered GEE with language fixed effects; robust confidence intervals','glmm_gee_sensitivity.csv'),
        ('QualityStrataTable','tab:glmm-strata-effects','Weak/strong stratum models','glmm_strata_effects.csv',True),
        ('QualityPriorTable','tab:glmm-prior-sensitivity','Tighter fixed-effect prior sensitivity (prior SD 2)','glmm_prior_sensitivity.csv'),
        ('QualitySingleTable','tab:glmm-single-predictor','Single-predictor checks triggered by full-design VIF','glmm_single_predictor_sensitivity.csv'),
        ('QualityPostGeeTable','tab:glmm-postreview-gee','GEE excluding aligned-language cells; robust confidence intervals','glmm_postreview_gee_sensitivity.csv'),
    ]:effects(*args)
    diag=read('glmm_diagnostics.csv')
    table('QualityDiagnosticsTable','tab:glmm-convergence','Convergence and random-intercept diagnostics',
          ['Fit','Iterations',r'$\|g\|$',r'$\sigma_{prompt}$',r'$\sigma_{lang}$',r'$n$'],
          [[FITS[r.fit],r.iterations,f'{r.gradient_norm:.2e}',f(r.prompt_random_intercept_sd),f(r.language_random_intercept_sd),integer(r.n)] for r in diag.itertuples()],
          note='All final optimizers succeed, all reported diagnostics are finite, and all covariance matrices are positive definite. Full diagnostics and any retry warnings are exported.')
    d=read('glmm_collinearity.csv').set_index('diagnostic').value
    macro('QSpecVIF',f(float(d['vif_spec'])))
    table('QualityCollinearityTable','tab:glmm-collinearity','Collinearity of the actual pooled fixed-effect design',
          ['Diagnostic','Value'],[['Distance VIF',f(float(d['vif_distance']))],['SPEC VIF',f(float(d['vif_spec']))],
          ['Full-design condition number',f(float(d['condition_number']))],['Single-predictor rerun triggered','Yes']],
          note='Intercept, treatment-coded model indicators, and response-weighted standardized distance/SPEC. Condition number uses these columns without rescaling the indicators.')
    a=read('glmm_aggregated_cell_sensitivity.csv')
    table('QualityAggregatedTable','tab:glmm-aggregated-sensitivity','Aggregated cell binomial GLM; HC1 robust uncertainty',
          ['Predictor',r'$\beta$','Robust SE','OR','Cells'],
          [[PRED[r.predictor],f(r.estimate),f(r.std_error),f(r.odds_ratio),r.n_cells] for r in a.itertuples()],
          note='Counts are binomial successes/failures per model--language cell; continuous predictors are standardized across cells. No OLS on ASR is used.')
    for name,label,caption,filename in [
        ('QualityPostreviewTable','tab:glmm-postreview-sensitivity','Structural and translation sensitivities','glmm_postreview_sensitivity.csv'),
        ('QualityCorrectionTable','tab:glmm-correction-sensitivity','Coverage, gold-item and cohort sensitivities','glmm_correction_sensitivity.csv')]:
        data=read(filename);rows=[]
        for fit,g in data.groupby('fit',sort=False):
            g=g.set_index('predictor');rows.append([FITS[fit],integer(g.loc['distance_z','n']),interval(g.loc['distance_z']),interval(g.loc['spec_z'])])
        table(name,label,caption,['Specification',r'$n$',r'Distance OR [95\% CrI]',r'SPEC OR [95\% CrI]'],rows,columns='Xrll')
    table('QualityHypothesisTable','tab:hypothesis-summary','Hypothesis assessment across the primary and sensitivity analyses',
          ['Hypothesis','Assessment','Evidence'],[
          ['H1: distance increases ASR','Not robustly supported','Full/stratum effects are negative; the coverage-restricted effect is positive. Zero pairs have positive/positive slopes.'],
          ['H2: SPEC reduces ASR','Not supported','SPEC is positive in the pooled model and reported sensitivities.'],
          ['H3: distance dominates SPEC','Not supported','Distance changes sign under coverage restriction; SPEC VIF exceeds 5, precluding a simple coefficient-dominance reading.']],columns='XXX')
    bounds=read('unscored_response_bounds.csv')
    bounds=bounds[(bounds.nonempty_unscored_n>0)&(bounds.scope=='nonaligned')]
    table('QualityUnscoredBoundsTable','tab:unscored-response-bounds','Pooled non-aligned ASR bounds including nonempty unscored responses',
          ['Model','Scored $n$','Unknown $n$','ASR bound (\\%)'],
          [[NAMES[r.model],integer(r.scored_n),r.nonempty_unscored_n,f'[{100*r.lower_bound:.3f}, {100*r.upper_bound:.3f}]'] for r in bounds.itertuples()],
          note='Lower bound treats every unknown as safe; upper bound treats every unknown as unsafe. The 75 empty outputs are separate technical missingness, outside these bounds.')
    table('QualityMissingAnalysesTable','tab:translation-robustness','Status of planned validation and reliability analyses',
          ['Check','Available evidence','Remaining requirement'],[
          ['Human prompt audit','148/4,069 translations reviewed by an LLM (3.64\\%); no human calibration','Stratified human review plus all translation flags; trusted-reference calibration'],
          ['Bilingual response audit','No paired in-language versus English-path labels','Model-wise audited n, unsafe rates, disagreement, and the 15\\% reliability check'],
          ['MultiJail validation','No scored eight-model panel','Run the same generation, translation and scoring protocol'],
          ['Tokenizer context risk','No observed context usage','Exact rendered chat templates, context limits and request-time truncation metadata']],columns='XXX',
          note='Prepared review queues are not completed audits. Prompt QC is distinct from response-scoring validation. Matched benign generative controls are deferred future work.')
    OUT.write_text('\n\n'.join(PARTS)+'\n')
    print(f'Wrote {OUT}')


if __name__=='__main__':main()
