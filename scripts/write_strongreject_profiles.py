"""Render per-language graded profiles without changing released estimates."""
import csv
import hashlib
import json
from pathlib import Path
import shutil
from write_belebele_profiles import PAIRS

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'eval/outputs/releases/2026-09-29-graded-reporting/cell_summary.csv'
RELEASE = ROOT / 'eval/outputs/releases/2026-10-11-strongreject-profiles'
FIGURE = ROOT / 'ufscthesisx/ufscthesisx/figures/strongreject_profiles.tex'
rows = list(csv.DictReader(SOURCE.open()))
cells = {(r['model'], r['attack_language']): r for r in rows}
assert len(cells) == len(rows) == 117
lines = [
    '% Generated by eval/scripts/write_strongreject_profiles.py; released estimates unchanged.',
    r'\definecolor{srweak}{RGB}{35,103,159}',
    r'\definecolor{srstrong}{RGB}{202,86,42}',
    r'\begin{tikzpicture}',
    r'\pgfplotsset{srprofile/.style={width=7.05cm,height=3.15cm,scale only axis,',
    r'xmin=-.4,xmax=12.4,ymin=0,ymax=1,ytick={0,.2,.4,.6,.8,1},',
    r'axis lines=box,grid=major,grid style={black!12},',
    r'tick label style={font=\scriptsize},label style={font=\footnotesize},',
    r'title style={font=\bfseries\small},xtick={0,...,12},',
    r'x tick label style={rotate=55,anchor=east,font=\scriptsize},ylabel={Mean score}}}',
    r'\node[anchor=south,font=\small\bfseries] at (3.5,.65) {Weak targets};',
    r'\node[anchor=south,font=\small\bfseries] at (12.05,.65) {Strong targets};',
]
for y, (pair, aligned, models) in enumerate(PAIRS):
    for x, (model, name) in enumerate(models):
        group = [r for r in rows if r['model'] == model]
        assert len(group) == 13
        group.sort(key=lambda r: (float(r['distance']), r['attack_language']))
        order = [r['attack_language'] for r in group]
        assert order[0] == aligned
        ticklabels = ','.join(r'\textbf{' + lang + '}' if lang == aligned else lang for lang in order)
        color = 'srweak' if x == 0 else 'srstrong'
        lines += [
            rf'\begin{{axis}}[srprofile,at={{({8.55*x:.2f}cm,{-4.8*y:.2f}cm)}},anchor=north west,',
            rf'title={{{name}}},xticklabels={{{ticklabels}}}]',
            r'\path[fill=black!7] (axis cs:-.35,0) rectangle (axis cs:.35,1);',
        ]
        coords = ' '.join(f"({i},{float(r['mean_score']):.6f})" for i, r in enumerate(group))
        bars = ' '.join(f"({i},{float(r['mean_score']):.6f}) += (0,{float(r['mean_ci_high'])-float(r['mean_score']):.6f}) -= (0,{float(r['mean_score'])-float(r['mean_ci_low']):.6f})" for i,r in enumerate(group))
        lines += [
            rf'\addplot[color={color},mark=*,mark size=1.7pt,line width=.75pt] coordinates {{{coords}}};',
            rf'\addplot[color={color},opacity=.65,only marks,mark=none,error bars/.cd,y dir=both,y explicit] coordinates {{{bars}}};',
            r'\end{axis}',
        ]
lines.append(r'\end{tikzpicture}')
FIGURE.write_text('\n'.join(lines)+'\n')
RELEASE.mkdir(parents=True, exist_ok=True)
shutil.copy2(FIGURE, RELEASE / FIGURE.name)
shutil.copy2(__file__, RELEASE / Path(__file__).name)
shutil.copy2(Path(__file__).with_name('write_belebele_profiles.py'), RELEASE / 'write_belebele_profiles.py')
manifest = {
    'purpose': 'Presentation only; per-language StrongREJECT profiles using saved means and intervals.',
    'source': str(SOURCE.relative_to(ROOT)),
    'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    'figure_sha256': hashlib.sha256(FIGURE.read_bytes()).hexdigest(),
    'code_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    'estimate_changes': False,
    'intervals': 'Saved 95% source-prompt cluster percentile bootstrap intervals, 2000 draws.',
    'axis': 'Equal language spacing, ordered by increasing within-model URIEL+ distance; not metric distance spacing.',
}
(RELEASE / 'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')
print(FIGURE)
