"""Inference-robustness release: cluster sensitivity, outcome decomposition,
descriptive ASR identity, and the pre-specified pair sign-retention matrix.

Run from eval: PYTHONPATH=src .venv/bin/python scripts/write_robustness_release.py

Adds no new experiment. Every number here is recomputed from the corrected
frozen dataset and the completed magnitude fits; frozen scores are never edited.
"""
from pathlib import Path
import hashlib
import json

import numpy as np
import pandas as pd

from thesis_eval.analysis.magnitude import fit_cluster_variants
from thesis_eval.analysis.reporting import (
    prereg_distance_slope_retention,
    prereg_falsification_summary,
)

ROOT = Path(__file__).resolve().parents[2]
E = ROOT / 'eval'
T = ROOT / 'ufscthesisx/ufscthesisx'
SRC = E / 'outputs/releases/2026-09-29-score-magnitude-v2'
CORRECTED = E / 'outputs/releases/2026-09-09-corrected'
OUT = E / 'outputs/releases/2026-10-16-inference-robustness'
OUT.mkdir(parents=True, exist_ok=True)

NAMES = {'sagui_7b': 'Sagui-7B', 'sabia_3': 'Sabi\\\'a-3',
         'llamantino_2_ultrachat_7b': 'LLaMAntino-2', 'llamantino_anita_8b': 'ANITA',
         'gpt_sw3': 'GPT-SW3', 'ai_sweden_llama3_8b': 'AI Sweden',
         'bggpt_7b': 'BgGPT-7B', 'bggpt_gemma_9b': 'BgGPT-Gemma',
         'llama3_1_8b_reference': 'English reference'}
COHORT_LABELS = {'pooled': 'Pooled', 'non_aligned': 'Non-aligned',
                 'cons_at_least_100': 'CONS coverage $\\geq$100',
                 'weak': 'Weak pole', 'strong': 'Strong pole'}
CLUSTER_LABELS = {'prompt_id': 'Source prompt', 'cell': 'Model--language cell',
                  'twoway': 'Two-way'}
MAIN = ('distance', 'spec_score')
PRED_LABELS = {'distance': 'Distance', 'spec_score': 'SPEC',
               'if_score': 'IF', 'cons_score': 'CONS'}

PARTS = ['% Generated by eval/scripts/write_robustness_release.py.',
         '% Inference robustness: clustering, outcome decomposition, pre-specified pair matrix.']


def macro(name, value):
    PARTS.append('\\newcommand{\\' + name + '}{' + str(value) + '}')


def table(name, label, caption, headers, rows, note='', align=None, plain=False):
    spec = align or ('X' + 'r' * (len(headers) - 1))
    if plain:
        # Plain full-width tabular: ltablex turns tabularx into a longtable,
        # which overflows the page when placed inside a table float.
        body = [r'\begin{table}[htbp]\centering\small',
                r'\caption{' + caption + '}' + r'\label{' + label + '}',
                r'\setlength{\tabcolsep}{4pt}',
                r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + spec + '@{}}',
                r'\toprule',
                ' & '.join(headers) + r' \\',
                r'\midrule']
        end = r'\bottomrule\end{tabular*}'
    else:
        body = [r'\begin{table}[htbp]\centering\small',
                r'\setlength{\tabcolsep}{4pt}',
                r'\begin{tabularx}{\linewidth}{' + spec + '}',
                r'\caption{' + caption + '}' + r'\label{' + label + '} \\\\',
                r'\toprule',
                ' & '.join(headers) + r' \\',
                r'\midrule']
        end = r'\bottomrule\end{tabularx}'
    body += [' & '.join(str(v) for v in row) + r' \\' for row in rows]
    body += [end,
             r'\par\smallskip\footnotesize ' + note,
             r'\fonte{Prepared by the author (2026).}',
             r'\end{table}']
    macro(name, '\n' + '\n'.join(body) + '\n')


def fmt(x, places=3):
    return 'n/a' if x is None or not np.isfinite(float(x)) else f'{float(x):.{places}f}'


def interval(estimate, low, high):
    return f'{fmt(estimate)} [{fmt(low)}, {fmt(high)}]'


# ---------------------------------------------------------------- load
raw = pd.read_json(CORRECTED / 'dataset_corrected.jsonl', lines=True)
scored = raw.loc[~raw.excluded & raw.strongreject_score.notna()].copy()
paired = scored.loc[scored.model_alignment_pole.isin(['weak', 'strong'])].copy()
coverage = pd.read_csv(CORRECTED / 'tables/belebele_coverage.csv')
enough = set(map(tuple, coverage.loc[coverage.n_cons_comparable >= 100,
                                     ['model', 'attack_language']].to_numpy()))
keys = list(zip(paired.model, paired.attack_language))

cohorts = [
    ('pooled', paired),
    ('non_aligned', paired.loc[paired.attack_language != paired.aligned_language]),
    ('cons_at_least_100', paired.loc[[k in enough for k in keys]]),
    ('weak', paired.loc[paired.model_alignment_pole == 'weak']),
    ('strong', paired.loc[paired.model_alignment_pole == 'strong']),
]

# ------------------------------------------------- 1. cluster sensitivity
variants = []
for name, data in cohorts:
    data = data.dropna(subset=list(MAIN)).reset_index(drop=True)
    print(f'Clustering variants for {name}: {len(data)} rows', flush=True)
    variants += fit_cluster_variants(data, MAIN, name)
cluster_frame = pd.DataFrame(variants).drop(columns=['scaling'])
cluster_frame.to_csv(OUT / 'cluster_sensitivity.csv', index=False)


def cvar(fit, cluster, predictor):
    hit = cluster_frame[(cluster_frame.fit == fit) & (cluster_frame.cluster == cluster)
                        & (cluster_frame.predictor == predictor)]
    return hit.iloc[0]


# -------------------------------------------- 2. outcome decomposition
effects = pd.read_csv(SRC / 'effects.csv')


def eff(fit, outcome, predictor):
    hit = effects[(effects.fit == fit) & (effects.outcome == outcome)
                  & (effects.predictor == predictor)]
    return hit.iloc[0]


decomposition = []
for fit in ('pooled', 'non_aligned'):
    for outcome in ('binary', 'score', 'positive_score'):
        for predictor in MAIN:
            r = eff(fit, outcome, predictor)
            decomposition.append(dict(fit=fit, outcome=outcome, predictor=predictor,
                                      n=int(r.n), estimate=float(r.estimate),
                                      ci_low=float(r.ci_low), ci_high=float(r.ci_high)))
pd.DataFrame(decomposition).to_csv(OUT / 'outcome_decomposition.csv', index=False)

# Sign tally for distance across every reported specification.
score_specs = effects[(effects.outcome == 'score') & (effects.predictor == 'distance')
                      & (~effects.fit.str.contains('_single_'))]
negative = int((score_specs.estimate < 0).sum())
total = int(len(score_specs))
score_specs.to_csv(OUT / 'distance_sign_tally.csv', index=False)

# ------------------------------------------------ 3. descriptive identity
summary = pd.read_csv(SRC / 'model_summary.csv')
identity = summary[(summary.scope == 'all_languages')
                   & (summary.model != 'paired_panel')].copy()
identity['asr_times_positive_mean'] = identity.asr * identity.positive_mean
identity.to_csv(OUT / 'descriptive_identity.csv', index=False)
panel = summary[(summary.model == 'paired_panel')].set_index('scope')

# ----------------------------------- 4. pre-specified sign-retention matrix
records = raw.to_dict('records')
pairs = prereg_distance_slope_retention(records)
prereg = prereg_falsification_summary(records)[0]
pd.DataFrame(pairs).to_csv(OUT / 'prereg_sign_retention.csv', index=False)
positive_pairs = sum(1 for p in pairs
                     if p['weak_slope_sign'] == 1 and p['strong_slope_sign'] == 1)
negative_pairs = sum(1 for p in pairs
                     if p['weak_slope_sign'] == -1 and p['strong_slope_sign'] == -1)
prereg_out = dict(prereg, positive_positive_pairs=positive_pairs,
                  negative_negative_pairs=negative_pairs)
(OUT / 'prereg_summary.json').write_text(json.dumps(prereg_out, indent=2) + '\n')

# ---------------------------------------------------------------- macros
macro('RNumCells', int(paired.groupby(['model', 'attack_language']).ngroups))
macro('RDistancePromptInterval', interval(*cvar('pooled', 'prompt_id', 'distance')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RDistanceCellInterval', interval(*cvar('pooled', 'cell', 'distance')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RSpecCellInterval', interval(*cvar('pooled', 'cell', 'spec_score')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RDistancePromptSE', fmt(cvar('pooled', 'prompt_id', 'distance').std_error))
macro('RDistanceCellSE', fmt(cvar('pooled', 'cell', 'distance').std_error))
macro('RSEInflation', fmt(cvar('pooled', 'cell', 'distance').std_error
                          / cvar('pooled', 'prompt_id', 'distance').std_error, 1))
macro('RNonAlignedDistanceCellInterval', interval(*cvar('non_aligned', 'cell', 'distance')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RNonAlignedSpecCellInterval', interval(*cvar('non_aligned', 'cell', 'spec_score')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RConsDistanceCellInterval', interval(*cvar('cons_at_least_100', 'cell', 'distance')[
    ['estimate', 'ci_low', 'ci_high']]))
macro('RDistanceNegativeCount', negative)
macro('RDistanceSpecCount', total)
macro('RPreregRetained', int(prereg['pairs_with_slope_sign_retained']))
macro('RPreregEvaluated', int(prereg['pairs_evaluated']))
macro('RPreregPositivePairs', positive_pairs)
macro('RPreregNegativePairs', negative_pairs)
macro('RAsrPooled', fmt(panel.loc['all_languages'].asr))
macro('RPositiveMeanPooled', fmt(panel.loc['all_languages'].positive_mean))
macro('RMeanPooled', fmt(panel.loc['all_languages'].mean_score))
macro('RAsrAligned', fmt(panel.loc['aligned'].asr))
macro('RAsrNonAligned', fmt(panel.loc['non_aligned'].asr))
macro('RPositiveMeanAligned', fmt(panel.loc['aligned'].positive_mean))
macro('RPositiveMeanNonAligned', fmt(panel.loc['non_aligned'].positive_mean))
macro('RBinaryDistanceInterval', interval(eff('pooled', 'binary', 'distance').estimate,
                                          eff('pooled', 'binary', 'distance').ci_low,
                                          eff('pooled', 'binary', 'distance').ci_high))
macro('RBinarySpecInterval', interval(eff('pooled', 'binary', 'spec_score').estimate,
                                      eff('pooled', 'binary', 'spec_score').ci_low,
                                      eff('pooled', 'binary', 'spec_score').ci_high))
macro('RPositiveDistanceInterval', interval(eff('pooled', 'positive_score', 'distance').estimate,
                                            eff('pooled', 'positive_score', 'distance').ci_low,
                                            eff('pooled', 'positive_score', 'distance').ci_high))
macro('RPositiveSpecInterval', interval(eff('pooled', 'positive_score', 'spec_score').estimate,
                                        eff('pooled', 'positive_score', 'spec_score').ci_low,
                                        eff('pooled', 'positive_score', 'spec_score').ci_high))
magnitudes = identity.positive_mean.astype(float)
macro('RPositiveMeanRange', f'{magnitudes.min():.3f}--{magnitudes.max():.3f}')
asrs = identity.asr.astype(float)
macro('RAsrRange', f'{asrs.min():.3f}--{asrs.max():.3f}')

# ---------------------------------------------------------------- tables
table('RClusterSensitivityTable', 'tab:cluster-sensitivity',
      'Graded coefficients under source-prompt, cell and two-way clustering',
      ['Cohort', 'Predictor', 'Clustering', 'Groups', 'Coefficient [95\\% CI]'],
      [[COHORT_LABELS[r.fit], PRED_LABELS[r.predictor], CLUSTER_LABELS[r.cluster],
        '--' if pd.isna(r.n_clusters) else int(r.n_clusters),
        interval(r.estimate, r.ci_low, r.ci_high)]
       for r in cluster_frame.itertuples()],
      'Point estimates are identical across clusterings by construction: working '
      'independence places the grouping in the sandwich covariance only. Distance and '
      'SPEC vary between model--language cells, so source-prompt clusters cut across '
      'the variation being tested. Two-way combines both dimensions and subtracts the '
      'row-level intersection.',
      align='llXrr')

table('ROutcomeDecompositionTable', 'tab:outcome-decomposition',
      'Frequency and conditional-magnitude components of the graded association',
      ['Cohort', 'Outcome', 'Scored $n$', 'Distance', 'SPEC'],
      [[COHORT_LABELS[fit],
        {'binary': 'Any compliance', 'score': 'Graded score',
         'positive_score': 'Score $\\mid$ score $>0$'}[outcome],
        f'{int(eff(fit, outcome, "distance").n):,}'.replace(',', '\\,'),
        interval(eff(fit, outcome, 'distance').estimate, eff(fit, outcome, 'distance').ci_low,
                 eff(fit, outcome, 'distance').ci_high),
        interval(eff(fit, outcome, 'spec_score').estimate, eff(fit, outcome, 'spec_score').ci_low,
                 eff(fit, outcome, 'spec_score').ci_high)]
       for fit in ('pooled', 'non_aligned')
       for outcome in ('binary', 'score', 'positive_score')],
      'Identical design and cohort; only the outcome changes. The positive-only row '
      'conditions on the outcome and is an exploratory description of a selected '
      'subset. Intervals are source-prompt clustered, so Table~\\ref{tab:cluster-sensitivity} '
      'applies to them as well.',
      align='llrXX')

table('RDescriptiveIdentityTable', 'tab:descriptive-identity',
      'Frequency and conditional magnitude behind each mean score',
      ['Model', 'Scored $n$', 'Any compliance', 'Mean $\\mid$ $>0$', 'Mean score'],
      [[NAMES[r.model], f'{int(r.n):,}'.replace(',', '\\,'), fmt(r.asr),
        fmt(r.positive_mean), fmt(r.mean_score)]
       for r in identity.sort_values('mean_score', ascending=False).itertuples()],
      'Mean score is the product of the two preceding columns. Conditional magnitude '
      'varies far less across models than compliance frequency, so differences in mean '
      'score are predominantly frequency differences. Descriptive only.',
      align='Xrrrr')

table('RPreregRetentionTable', 'tab:prereg-sign-retention',
      'Pre-specified heterogeneous-pair distance-slope sign retention',
      ['Aligned language', 'Weak slope', 'Strong slope', 'Sign retained'],
      [[p['model_pair_language'],
        f"{fmt(p['weak_distance_slope'])} ({NAMES.get(p['weak_model'], p['weak_model'])})",
        f"{fmt(p['strong_distance_slope'])} ({NAMES.get(p['strong_model'], p['strong_model'])})",
        'yes' if p['slope_sign_retained'] else 'no']
       for p in pairs],
      'Within-model logistic distance slopes on the pre-specified binary outcome, '
      'estimated separately at each pole. The decision rule counts pairs retaining the '
      'same sign at both poles; this tests agreement of sign, not the positive sign '
      'H\\textsubscript{1} predicts, so positive/positive and negative/negative pairs '
      'are reported separately in the text.',
      align='llll', plain=True)

(T / 'chapters/robustness_assets.tex').write_text('\n\n'.join(PARTS) + '\n')

# ---------------------------------------------------------------- report
report = [
    '# Inference robustness', '',
    'Recomputed from the corrected frozen dataset and the completed magnitude fits. '
    'No new generation, scoring or translation. All four analyses below are '
    'post-review; only the pair sign-retention matrix was specified before results.',
    '', '## Clustering', '',
    f'Distance and SPEC vary between {int(paired.groupby(["model","attack_language"]).ngroups)} '
    'model-language cells, not between source prompts. Clustering on source prompts '
    'therefore cuts across the variation being tested.', '',
    '| Cohort | Predictor | Prompt-clustered | Cell-clustered |', '|---|---|---|---|']
for fit, _ in cohorts:
    for predictor in MAIN:
        p = cvar(fit, 'prompt_id', predictor)
        c = cvar(fit, 'cell', predictor)
        report.append(f'| {fit} | {predictor} | {interval(p.estimate, p.ci_low, p.ci_high)} '
                      f'| {interval(c.estimate, c.ci_low, c.ci_high)} |')
report += [
    '',
    f'Pooled distance standard error rises from {fmt(cvar("pooled","prompt_id","distance").std_error)} '
    f'to {fmt(cvar("pooled","cell","distance").std_error)} and the interval covers zero. '
    'The CONS-coverage cohort, previously described as reversing the sign, also covers '
    'zero. The two cohorts therefore do not disagree in any inferentially meaningful '
    'sense. SPEC remains bounded away from zero except in the strong-pole stratum.',
    '', '## Outcome decomposition', '',
    f'mean(score) = ASR x mean(score | score > 0): {fmt(panel.loc["all_languages"].mean_score)} = '
    f'{fmt(panel.loc["all_languages"].asr)} x {fmt(panel.loc["all_languages"].positive_mean)}.',
    '',
    f'Across models, compliance frequency spans {asrs.min():.3f}-{asrs.max():.3f} while '
    f'conditional magnitude spans only {magnitudes.min():.3f}-{magnitudes.max():.3f}. '
    'Distance behaves almost identically on all three outcomes; SPEC acts chiefly on '
    'whether the model complies at all, not on how useful the compliance is.',
    '', '## Distance sign tally', '',
    f'Distance is negative in {negative} of {total} reported specifications and positive in '
    f'{total - negative}. The single positive specification is the CONS-coverage '
    'restriction, which removes an entire model.',
    '', '## Pre-specified pair matrix', '',
    f'{prereg["pairs_with_slope_sign_retained"]} of {prereg["pairs_evaluated"]} pairs retain '
    f'the distance-slope sign: {prereg["interpretation"]}. Pairs positive at both poles '
    f'(the direction H1 predicts): {positive_pairs}. Pairs negative at both poles: '
    f'{negative_pairs}.', '']
(OUT / 'REPORT.md').write_text('\n'.join(report))

inputs = [CORRECTED / 'dataset_corrected.jsonl', CORRECTED / 'tables/belebele_coverage.csv',
          SRC / 'effects.csv', SRC / 'model_summary.csv']
manifest = dict(
    version=OUT.name, post_review=True,
    source_sha256={str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs},
    code_sha256={str(p): hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in [Path(__file__), E / 'src/thesis_eval/analysis/magnitude.py']},
    n_paired=int(len(paired)), n_cells=int(paired.groupby(['model', 'attack_language']).ngroups),
    cluster_variants=int(len(cluster_frame)),
    prereg=prereg_out,
    analysis='Cell and two-way clustered sandwich covariance for the graded fractional-logit '
             'mean equation; binary and positive-only outcome decomposition; descriptive ASR '
             'identity; pre-specified pair sign-retention matrix on the binary outcome.',
    limitations=[
        'Cell clustering requires a moderate number of clusters; with 104 cells the '
        'asymptotics are approximate and intervals should be read as indicative.',
        'Two-way covariance is not guaranteed positive definite; the table reports whether '
        'it was usable in each fit.',
        'Positive-only outcome conditions on the outcome and is not a causal intensity effect.',
        'The pair matrix tests sign agreement between poles, not the direction H1 predicts.',
        'No new data; all historical translation, judge and provenance limitations remain.'])
manifest['outputs_sha256'] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                              for p in OUT.iterdir() if p.is_file() and p.name != 'manifest.json'}
(OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(f'Wrote {OUT} and {T / "chapters/robustness_assets.tex"}')
