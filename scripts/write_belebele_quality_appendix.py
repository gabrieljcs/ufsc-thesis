"""Generate canonical BELEBELE examples and complete measurement coverage."""
from pathlib import Path
from collections import Counter
import subprocess,sys
import pandas as pd
from thesis_eval.benchmarks.belebele import canonical_question_id,load_belebele_rows,migrate_prediction_identities
from thesis_eval.io import read_jsonl
ROOT=Path(__file__).resolve().parents[2];E=ROOT/'eval';T=ROOT/'ufscthesisx/ufscthesisx'
NAMES={'sagui_7b':'Sagui-7B','sabia_3':r"Sabi\'a-3",'llamantino_2_ultrachat_7b':'LLaMAntino-2', 'llamantino_anita_8b':'ANITA','gpt_sw3':'GPT-SW3','ai_sweden_llama3_8b':'AI Sweden','bggpt_7b':'BgGPT-7B','bggpt_gemma_9b':'BgGPT-Gemma','llama3_1_8b_reference':'English reference'}
def esc(s):
 for a,b in [('\\',r'\textbackslash{}'),('&',r'\&'),('%',r'\%'),('_',r'\_'),('#',r'\#')]:s=str(s).replace(a,b)
 return s

def main():
 pred=migrate_prediction_identities(read_jsonl(E/'outputs/spec/all_belebele_predictions.jsonl'),E/'assets/datasets/belebele')
 source=load_belebele_rows(E/'assets/datasets/belebele','eng');lookup={(r['model'],r['language'],r['canonical_item_id']):r for r in pred}
 byquestion={canonical_question_id(r):[] for r in source}
 for r in pred:byquestion[r['canonical_item_id']].append(r)
 # Disclose how the four inspected items were chosen, rather than presenting them
 # as if they were an unbiased sample. Ranks are computed, never hand-entered.
 SELECTED=[150,175,302,847]
 def wrong_count(index):
  rows=byquestion[canonical_question_id(source[index-1])]
  return sum(1 for r in rows if r.get('predicted_choice') in list('ABCD') and r['predicted_choice']!=r['gold'])
 counts={i+1:wrong_count(i+1) for i in range(len(source))}
 order=sorted(counts,key=lambda i:-counts[i])
 rank={index:position for position,index in enumerate(order,start=1)}
 ranks=[rank[i] for i in SELECTED]
 global RANK_TEXT,NEAR_MISS
 RANK_TEXT=', '.join(str(r) for r in sorted(ranks)[:-1])+' and '+str(sorted(ranks)[-1])
 floor=min(counts[i] for i in SELECTED)
 NEAR_MISS=sum(1 for i,c in counts.items() if i not in SELECTED and c>=floor-5)
 text=[r'''% Generated by eval/scripts/write_belebele_quality_appendix.py.
\chapter{BELEBELE Coverage and Scoring Examples}
\label{app:belebele-scoring-examples}

All cross-language joins in this appendix use canonical question identity (passage link, split when present, and question number), not language-file row position. The English row numbers below are readable anchors only. Saved answer options and gold labels are validated against each source-language file. The analysis retains the supplied gold labels.

IF denotes instruction following, measured as BELEBELE answer accuracy; CONS denotes cross-lingual consistency, measured as answer agreement with the aligned language; and SPEC denotes specialization, the equal-weight average of their standardized values. Section~\ref{sec:post-training-specialization} defines the measures formally.

\section{Question-level checks}
The following four questions illustrate the scoring rules and source-label concerns. ``Incorrect'' counts parseable answers that differ from the source gold; ``unparsed'' counts missing A/B/C/D answers separately. IF counts an unparsed answer as not correct, whereas CONS excludes pairs lacking either parseable answer.

These four were not drawn at random. They were selected by inspecting the questions that the most models answered against the supplied gold, and they rank '''+RANK_TEXT+r''' of the 900 items by that count. The screen was therefore a scan of the upper tail of the error distribution, not a systematic audit: '''+str(NEAR_MISS)+r''' further items have incorrect-answer counts within five of the lowest-ranked example here and were not adjudicated. The two gold labels flagged below should accordingly be read as a lower bound on source-label problems in this benchmark, not as an exhaustive list, and the item-exclusion sensitivity tests only those two. A high model-error rate is itself weak evidence of a bad label, since a genuinely hard question produces the same pattern; each flag below rests on reading the passage, not on the count.
''']
 for index in [150,175,302,847]:
  src=source[index-1];key=canonical_question_id(src);rows=byquestion[key];n=len(rows)
  wrong=sum(r.get('predicted_choice') in 'ABCD' and r['predicted_choice']!=r['gold'] for r in rows if r.get('predicted_choice'))
  unparsed=sum(r.get('predicted_choice') not in ['A','B','C','D'] for r in rows)
  gold='ABCD'[int(src['correct_answer_num'])-1]
  text += [r'\subsection*{English source row '+str(index)+'}',esc(src['question']),r'\begin{description}']
  text += [r'\item['+letter+'] '+esc(src[f'mc_answer{num}']) for num,letter in enumerate('ABCD',1)]
  text += [r'\end{description}',f'Source gold: {gold}. Across {n} model--language predictions, {wrong} are incorrect and {unparsed} are unparsed.']
  if index==150:text += ['The source gold C (all seven wonders) is inconsistent with the passage, which identifies the Great Pyramid as the surviving wonder. This is a source-label concern, not evidence that all models misunderstood the passage.']
  if index==847:text += ['The source gold C is not supported by the described bus departures. Option A is better supported by the passage. This remains a flagged source-label question pending independent adjudication.']
 text += [r'''The sensitivity excluding both flagged question identities across all languages leaves the main regression estimates nearly unchanged (Table~\ref{tab:glmm-correction-sensitivity}). The main analysis retains the original gold labels.

\begin{table}[htbp]
\centering\small
\begin{tabularx}{\linewidth}{Xrrrrrr}
\caption{Canonical item-matched IF and CONS examples}
\label{tab:belebele-scoring-examples} \\
\toprule
Model / test & EN row & Gold & Aligned & Test & IF & CONS \\
\midrule''']
 aligned={r['model']:r['aligned_language'] for r in read_jsonl(E/'outputs/dataset_frozen.jsonl')}
 for model,lang,index in [('bggpt_7b','rus',847),('ai_sweden_llama3_8b','swa',150),('sabia_3','dan',150),('llamantino_2_ultrachat_7b','swa',150)]:
  key=canonical_question_id(source[index-1]);r=lookup[model,lang,key];base=lookup[model,aligned[model],key].get('predicted_choice');test=r.get('predicted_choice')
  cons='--' if base not in list('ABCD') or test not in list('ABCD') else str(int(base==test))
  text += [f"{NAMES[model]} / {lang} & {index} & {r['gold']} & {base or '--'} & {test or '--'} & {int(test==r['gold'])} & {cons}"+r' \\']
 text += [r'''\bottomrule
\end{tabularx}
\par\smallskip\footnotesize -- denotes an undefined comparison, not disagreement.
\fonte{Prepared by the author (2026), based on saved predictions joined by canonical identity.}
\end{table}

\section{Complete specialization coverage}
Each cell contains 900 attempted questions. IF is correct/900; Parse is the number of interpretable A/B/C/D answers; paired $n$ is the denominator of CONS. The bracketed CONS bounds are 95\% Wilson intervals conditional on the observed comparable subset. They do not account for informative parsing failures. SPEC uses the two component z-scores across all 117 evaluated cells, including the English reference. Aligned-language CONS equals one by construction when answers are parseable. The weak Italian model has particularly sparse paired coverage; its Russian CONS is based on four answers, so the apparent perfect consistency is highly uncertain.
''']
 coverage=pd.read_csv(E/'outputs/releases/2026-09-09-corrected/tables/belebele_coverage.csv')
 for model,name in NAMES.items():
  text += [r'\begin{table}[htbp]',r'\centering\small',r'\begin{tabularx}{\linewidth}{Xrrrrr}',r'\caption{BELEBELE measurement coverage: '+name+r'} \\',r'\toprule',r'Language & Parse & IF & Paired $n$ & CONS [95\% CI] & SPEC \\',r'\midrule']
  for r in coverage[coverage.model==model].itertuples():
   text += [f'{r.attack_language} & {r.n_parseable} & {r.if_score:.3f} & {r.n_cons_comparable} & {r.cons_score:.3f} [{r.cons_ci_low:.3f}, {r.cons_ci_high:.3f}] & {r.spec_score:.3f}'+r' \\']
  text += [r'\bottomrule',r'\end{tabularx}',r'\fonte{Prepared by the author (2026), based on the versioned analysis supplement (Section~\ref{sec:code-data-availability}).}',r'\end{table}']
 (T/'aftertext/apendice_d.tex').write_text('\n\n'.join(text)+'\n')
 subprocess.run([sys.executable,str(E/'scripts/write_belebele_sparse_examples.py')],check=True)
 print('Wrote canonical BELEBELE appendix')
if __name__=='__main__':main()
