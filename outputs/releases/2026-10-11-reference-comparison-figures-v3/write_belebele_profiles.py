"""Generate native PGFPlots BELEBELE profiles from corrected released cells."""
import csv
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[2]
RELEASE = ROOT / 'eval/outputs/releases/2026-10-08-belebele-profiles-v2'
COVERAGE = ROOT / 'eval/outputs/releases/2026-09-09-corrected/tables/belebele_coverage.csv'
CELLS = ROOT / 'eval/outputs/releases/2026-09-29-graded-reporting/cell_summary.csv'
FIGURE = ROOT / 'ufscthesisx/ufscthesisx/figures/belebele_profiles.tex'
PAIRS = [
    ('Portuguese', 'por', [('sagui_7b', 'Sagui-7B'), ('sabia_3', r"Sabi\'a-3")]),
    ('Italian', 'ita', [('llamantino_2_ultrachat_7b', 'LLaMAntino-2'), ('llamantino_anita_8b', 'ANITA-8B')]),
    ('Swedish', 'swe', [('gpt_sw3', 'GPT-SW3'), ('ai_sweden_llama3_8b', 'AI Sweden')]),
    ('Bulgarian', 'bul', [('bggpt_7b', 'BgGPT-7B'), ('bggpt_gemma_9b', 'BgGPT-Gemma')]),
]

def main():
    RELEASE.mkdir(parents=True, exist_ok=True)
    coverage = list(csv.DictReader(COVERAGE.open()))
    distances = {(r['model'], r['attack_language']): r['distance'] for r in csv.DictReader(CELLS.open())}
    assert len(distances) == 117
    lines = [
        '% Generated by eval/scripts/write_belebele_profiles.py; released scores unchanged.',
        r'\definecolor{belebeleif}{RGB}{35,103,159}',
        r'\definecolor{belebelecons}{RGB}{202,86,42}',
        r'\definecolor{belebelespec}{RGB}{38,132,109}',
        r'\begin{tikzpicture}',
                r'\pgfplotsset{belebeleaxis/.style={width=7.05cm,scale only axis,xmin=-.4,xmax=12.4,',
        r'axis lines=box,grid=major,grid style={black!12},',
        r'tick label style={font=\scriptsize},label style={font=\footnotesize},',
        r'title style={font=\bfseries\small},unbounded coords=jump,',
        r'clip=true,xtick={0,...,12}}}',
        r'\node[anchor=south,draw=black!20,fill=white,inner sep=4pt,font=\scriptsize] at (7.8,.65) {\textcolor{belebeleif}{$\bullet$ IF (accuracy)}\quad',
        r'\textcolor{belebelecons}{$\bullet$ CONS (agreement)}\quad',
        r'\textcolor{belebelespec}{$\bullet$ SPEC}\quad $\circ$ Paired $n<100$};',
    ]
    plotted = []
    for row, (language, aligned, models) in enumerate(PAIRS):
        for col, (model, name) in enumerate(models):
            cell = [dict(r, distance=distances[model, r['attack_language']]) for r in coverage if r['model'] == model]
            cell.sort(key=lambda r: (float(r['distance']), r['attack_language']))
            assert len(cell) == 13 and cell[0]['attack_language'] == aligned
            assert all(r[k] and float(r[k]) == float(r[k]) for r in cell for k in ['if_score', 'cons_score', 'spec_score'])
            for i, r in enumerate(cell):
                r['plot_order'] = i
                plotted.append(r)
            xpos = col * 8.55
            ypos = -row * 5.65
            labels = ','.join((r'\textbf{' + r['attack_language'] + '}' if i == 0 else r['attack_language']) for i, r in enumerate(cell))
            def coords(metric, selector=lambda r: True, gaps=False):
                return ' '.join(f"({i},{float(r[metric]):.6f})" if selector(r) else (f'({i},nan)' if gaps else '') for i, r in enumerate(cell))
            sparse = lambda r: int(r['n_cons_comparable']) < 100
            reliable = lambda r: not sparse(r)
            lines += [r'\begin{axis}[belebeleaxis,height=2.2cm,at={('+f'{xpos:.2f}cm,{ypos:.2f}cm'+r')},anchor=north west,',
                      'title={'+name+'},',
                      r'ymin=-.03,ymax=1.06,ytick={0,.2,.4,.6,.8,1},xticklabels=\empty,' + r'ylabel={IF / CONS}' + ']',
                      r'\path[fill=black!7] (axis cs:-.35,-.03) rectangle (axis cs:.35,1.06);',
                      r'\addplot[color=belebeleif,mark=*,mark size=1.5pt,line width=.75pt] coordinates {'+coords('if_score')+'};',
                      r'\addplot[color=belebelecons,mark=*,mark size=1.5pt,line width=.75pt] coordinates {'+coords('cons_score', reliable, True)+'};']
            # Wilson intervals are conditional on the comparable subset, not parse failures.
            errors = ' '.join(f"({i},{float(r['cons_score']):.6f}) += (0,{float(r['cons_ci_high'])-float(r['cons_score']):.6f}) -= (0,{float(r['cons_score'])-float(r['cons_ci_low']):.6f})" for i,r in enumerate(cell))
            lines += [r'\addplot[color=belebelecons,opacity=.45,only marks,mark=none,error bars/.cd,y dir=both,y explicit] coordinates {'+errors+'};',
                      r'\addplot[color=belebelecons,only marks,mark=o,mark options={fill=white},mark size=1.8pt] coordinates {'+coords('cons_score',sparse)+'};',
                      r'\end{axis}',
                      r'\begin{axis}[belebeleaxis,height=1.5cm,at={('+f'{xpos:.2f}cm,{ypos-2.45:.2f}cm'+r')},anchor=north west,',
                      r'ymin=-2.65,ymax=2.15,ytick={-2,0,2},xticklabels={'+labels+r'},x tick label style={rotate=55,anchor=east,font=\scriptsize},' + r'ylabel={SPEC}' + ']',
                      r'\path[fill=black!7] (axis cs:-.35,-2.65) rectangle (axis cs:.35,2.15);',
                      r'\addplot[black!45,dashed,mark=none] coordinates {(-.4,0) (12.4,0)};',
                      r'\addplot[color=belebelespec,mark=*,mark size=1.5pt,line width=.75pt] coordinates {'+coords('spec_score',reliable,True)+'};',
                      r'\addplot[color=belebelespec,only marks,mark=o,mark options={fill=white},mark size=1.9pt] coordinates {'+coords('spec_score',sparse)+'};',
                      r'\end{axis}']
    assert len(plotted) == 104
    assert all(-2.65 <= float(r['spec_score']) <= 2.15 for r in plotted)
    lines += [r'\end{tikzpicture}']
    FIGURE.write_text('\n'.join(lines)+'\n')
    shutil.copy2(FIGURE, RELEASE / FIGURE.name)
    shutil.copy2(Path(__file__), RELEASE / Path(__file__).name)
    with (RELEASE / 'plotted_cells.csv').open('w', newline='') as f:
        writer = csv.DictWriter(f,fieldnames=list(plotted[0]))
        writer.writeheader(); writer.writerows(plotted)
    files = [COVERAGE,CELLS,Path(__file__),FIGURE,RELEASE/'plotted_cells.csv']
    manifest = {'revision':'Style matched to paired StrongREJECT PGFPlots: boxed axes, shared type sizes, line widths and circular markers; frozen measurements unchanged.',
                'spec_standardization':'All 117 evaluated cells, including English reference.',
                'sparse_marker_rule':'n_cons_comparable < 100; sparse CONS and SPEC points do not connect.',
                'checksums':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in files}}
    (RELEASE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__ == '__main__':
    main()
