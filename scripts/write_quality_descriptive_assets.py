"""Generate every descriptive Results table from saved versioned evidence."""
from pathlib import Path
import json
import pandas as pd
import numpy as np
import write_quality_latex_assets as q
ROOT=Path(__file__).resolve().parents[2];E=ROOT/'eval';T=ROOT/'ufscthesisx/ufscthesisx'
REL=E/'outputs/releases/2026-09-09-corrected'
TARGET=list(q.NAMES)[:-1]

def pct(x):return f'{100*x:.1f}'
def prompt_qc_table(rows):
 names={'ara':'Arabic','bul':'Bulgarian','dan':'Danish','eng':'English',
        'fin':'Finnish','ita':'Italian','nor':'Norwegian','por':'Portuguese',
        'rus':'Russian','spa':'Spanish','swa':'Swahili','swe':'Swedish','ukr':'Ukrainian'}
 lines=[r'\newcommand{\QualityPromptQcTable}{%',r'\begin{table}[htbp]',
        r'\centering\small',
        r'\caption{LLM-only prompt-translation QC on the BLASER-flagged queue}',
        r'\label{tab:prompt-translation-qc}',r'\begingroup',
        r'\setlength{\tabcolsep}{10pt}',r'\renewcommand{\arraystretch}{1.15}',
        r'\begin{tabular}{lrrrr}',r'\toprule',
        r'Language & Flagged $n$ & Median XSTS & Retained & Excluded \\',r'\midrule']
 for lang,n,median,retained,excluded in rows:
  lines.append(f'{names[lang]} & {n} & {median} & {retained} & {excluded}'+r' \\')
 lines += [r'\midrule',
           f"Total & {sum(int(r[1]) for r in rows)} & "+r'\textemdash'+f" & {sum(int(r[3]) for r in rows)} & {sum(int(r[4]) for r in rows)}"+r' \\',
           r'\bottomrule',r'\end{tabular}',r'\endgroup',r'\fonte{Prepared by the author (2026).}',r'\end{table}',r'}']
 return '\n'.join(lines)

def main():
 q.PARTS[:]=['% Generated by eval/scripts/write_quality_descriptive_assets.py; do not edit values.']
 data=pd.read_parquet(REL/'dataset_corrected.parquet');valid=data[(~data.excluded)&data.unsafe_binary.notna()]
 meta=data.groupby('model').aligned_language.first()
 coverage=q.read('results_coverage.csv').set_index('model')
 q.table('QualityCoverageTable','tab:results-coverage','Evaluation coverage and data quality by model',
         ['Model','Langs.','Attempts','API (\\%)','Block (\\%)','Unscored (\\%)','Refusal (\\%)'],
         [[name,13,int(coverage.loc[m,'total_attempts']),pct(coverage.loc[m,'api_failure_rate']),pct(coverage.loc[m,'provider_block_rate']),pct(coverage.loc[m,'scoring_failure_rate']),pct(coverage.loc[m,'refusal_rate'])] for m,name in q.NAMES.items()],columns='Xrrrrrr',note='The excluded/unscored column includes empty outputs and judge-scoring failures. Refusals remain in the scored denominator; zero provider blocks means no recorded block.',
         source='Prepared by the author (2026).')
 for aligned,macro,label,caption in [(True,'QualityAlignedTable','tab:aligned-language-baseline-asr','Aligned-language baseline ASR'),(False,'QualityOverallTable','tab:overall-asr','Pooled non-aligned ASR')]:
  rows=[]
  for m in TARGET:
   group=valid[(valid.model==m)&((valid.attack_language==meta[m])==aligned)];n=len(group);k=int(group.unsafe_binary.sum())
   from write_thesis_results_latex_assets import wilson
   low,high=wilson(k,n)
   rows.append([q.NAMES[m],q.integer(n),pct(k/n),f'[{100*low:.1f}, {100*high:.1f}]',q.f(group.strongreject_score.mean()),pct(group.refusal_binary.mean())])
  q.table(macro,label,caption,['Model',r'$n$','ASR (\\%)','95\\% CI','Mean score','Refusal (\\%)'],rows,
          note='Wilson binomial intervals are descriptive; pooled estimates reuse prompt identities across languages. Scores and refusals use the same scored cohort.')
 cf=q.read('closest_farthest_languages.csv').set_index('model')
 q.table('QualityClosestTable','tab:closest-farthest-languages','Closest and farthest language by model, including the aligned baseline',
         ['Model','Closest','ASR (\\%)','Farthest','ASR (\\%)','Gap (pp)'],
         [[q.NAMES[m],cf.loc[m,'closest_language'],pct(cf.loc[m,'closest_asr']),cf.loc[m,'farthest_language'],pct(cf.loc[m,'farthest_asr']),pct(cf.loc[m,'gap'])] for m in TARGET])
 ref=q.read('reference_distance_curve.csv')
 q.table('QualityReferenceTable','tab:reference-distance-curve','Per-language English-reference ASR, ordered by distance',
         ['Language','Distance','ASR (\\%)','Mean score','Refusal (\\%)'],
         [[r.attack_language,q.f(r.distance_from_english),pct(r.asr),q.f(r.mean_strongreject_score),pct(r.refusal_rate)] for r in ref.itertuples()])
 comparison=q.read('counterfactual_safety_by_aligned_language.csv').set_index('model')
 q.table('QualityComparisonTable','tab:counterfactual-safety','Aligned-language comparison with the English reference',
         ['Model','Language','Model ASR (\\%)','Reference ASR (\\%)','Gap (pp)'],
         [[q.NAMES[m],comparison.loc[m,'aligned_language'],pct(comparison.loc[m,'model_asr']),pct(comparison.loc[m,'reference_asr_same_language']),pct(comparison.loc[m,'asr_gap_model_minus_reference'])] for m in TARGET],
         note='Checkpoint comparison; the reference is neither a measured parent model nor a causal counterfactual.')
 corr=q.read('distance_asr_correlation.csv').set_index('model')
 q.table('QualityDistanceCorrelationTable','tab:distance-asr-correlation','Descriptive distance--ASR Spearman correlations',
         ['Model','Languages',r'$\rho$','95\\% bootstrap interval'],
         [[name,int(corr.loc[m,'n']),q.f(corr.loc[m,'spearman_rho']),f"[{corr.loc[m,'ci_low']:.3f}, {corr.loc[m,'ci_high']:.3f}]"] for m,name in q.NAMES.items()],
         note='Bootstrap over the purposive language inventory; not population-level language inference.')
 slopes=q.read('prereg_distance_slope_retention.csv')
 q.table('QualityPairSignsTable','tab:distance-slope-retention','Pre-specified pair sign check with directional interpretation',
         ['Pair language','Weak slope','Strong slope','Matching signs'],
         [[r.model_pair_language,q.f(r.weak_distance_slope),q.f(r.strong_distance_slope),'Both negative' if r.slope_sign_retained else 'No'] for r in slopes.itertuples()],
         note='Zero positive/positive pairs; the sole matching pair is negative/negative.')
 auditrows=[]
 for lang in sorted(data.attack_language.unique()):
  audit=pd.read_csv(E/f'outputs/audit/{lang}.xsts_decisions.csv')
  scores=pd.to_numeric(audit.get('xsts_score',pd.Series(dtype=float)),errors='coerce').dropna()
  auditrows.append([lang,len(audit),'--' if scores.empty else f'{scores.median():.1f}',int((audit.audit_decision=='pass').sum()),int((audit.audit_decision=='exclude').sum())])
 q.PARTS.append(prompt_qc_table(auditrows))
 # Shared prompt-cluster resampling retains within-prompt language dependence.
 ids=sorted(valid.prompt_id.unique());rng=np.random.default_rng(20260909)
 weights=rng.multinomial(len(ids),np.full(len(ids),1/len(ids)),size=5000)
 bootrows=[]
 for m,name in q.NAMES.items():
  group=valid[(valid.model==m)&(valid.attack_language!=meta[m])]
  counts=group.groupby('prompt_id').unsafe_binary.agg(['sum','count']).reindex(ids,fill_value=0)
  draws=(weights@counts['sum'].to_numpy())/(weights@counts['count'].to_numpy())
  lo,hi=np.quantile(draws,[.025,.975]);value=group.unsafe_binary.mean()
  bootrows.append(dict(model=m,asr=value,ci_low=lo,ci_high=hi,n=len(group),bootstrap_replicates=5000,seed=20260909))
 pd.DataFrame(bootrows).to_csv(REL/'tables/asr_prompt_cluster_bootstrap.csv',index=False)
 q.table('QualityClusterAsrTable','tab:asr-cluster-bootstrap','Pooled non-aligned ASR: prompt-cluster bootstrap intervals',
         ['Model',r'$n$','ASR (\\%)','95\\% cluster interval'],
         [[q.NAMES[r['model']],q.integer(r['n']),pct(r['asr']),f"[{100*r['ci_low']:.1f}, {100*r['ci_high']:.1f}]"] for r in bootrows],
         note='5,000 percentile draws of the 313 prompt identities, retaining all available non-aligned languages within each selected prompt. Supplementary uncertainty check, conditional on this model/language panel.')
 (T/'chapters/quality_descriptive_assets.tex').write_text('\n\n'.join(q.PARTS)+'\n')
 print('Wrote generated descriptive tables and cluster bootstrap')
if __name__=='__main__':main()
