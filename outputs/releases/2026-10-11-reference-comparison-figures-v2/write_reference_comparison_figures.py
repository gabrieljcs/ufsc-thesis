"""Add descriptive English-reference panels to three comparison figures.

Use saved measurements only; export a new presentation release.
"""
import csv
import hashlib
import json
import os
from pathlib import Path
import runpy
import shutil
import re

ROOT = Path(__file__).resolve().parents[2]
RELEASE = ROOT / 'eval/outputs/releases/2026-10-11-reference-comparison-figures-v2'
FIGURES = ROOT / 'ufscthesisx/ufscthesisx/figures'
CELLS = ROOT / 'eval/outputs/releases/2026-09-29-graded-reporting/cell_summary.csv'
COVERAGE = ROOT / 'eval/outputs/releases/2026-09-09-corrected/tables/belebele_coverage.csv'
REF = 'llama3_1_8b_reference'
PAIRS = [
 ('por', [('sagui_7b','Sagui-7B'),('sabia_3',r"Sabi\'a-3")]),
 ('ita', [('llamantino_2_ultrachat_7b','LLaMAntino-2'),('llamantino_anita_8b','ANITA-8B')]),
 ('swe', [('gpt_sw3','GPT-SW3'),('ai_sweden_llama3_8b','AI Sweden')]),
 ('bul', [('bggpt_7b','BgGPT-7B'),('bggpt_gemma_9b','BgGPT-Gemma')]),
]
rows = list(csv.DictReader(CELLS.open()))
coverage = list(csv.DictReader(COVERAGE.open()))
assert len(rows) == len(coverage) == 117
RELEASE.mkdir(parents=True, exist_ok=True)

def group(model):
 g = [r for r in rows if r['model'] == model]
 assert len(g) == 13
 return sorted(g,key=lambda r:(float(r['distance']),r['attack_language']))

def labels(g, aligned):
 return ','.join(r'\textbf{'+r['attack_language']+'}' if r['attack_language']==aligned else r['attack_language'] for r in g)

# StrongREJECT: four paired rows, then one centred reference panel.
lines = [r'\definecolor{srweak}{RGB}{35,103,159}',r'\definecolor{srstrong}{RGB}{202,86,42}',r'\begin{tikzpicture}',
 r'\pgfplotsset{srprofile/.style={width=7.05cm,height=2.65cm,scale only axis,xmin=-.4,xmax=12.4,ymin=0,ymax=1,ytick={0,.2,.4,.6,.8,1},axis lines=box,grid=major,grid style={black!12},tick label style={font=\scriptsize},label style={font=\footnotesize},title style={font=\bfseries\small},xtick={0,...,12},x tick label style={rotate=55,anchor=east,font=\scriptsize},ylabel={Mean score}}}',
 r'\node[anchor=south,font=\small\bfseries] at (3.5,.65) {Weak targets};',r'\node[anchor=south,font=\small\bfseries] at (12.05,.65) {Strong targets};']
entries = [(m,n,a,8.55*x,-4.15*y,'srweak' if x==0 else 'srstrong') for y,(a,models) in enumerate(PAIRS) for x,(m,n) in enumerate(models)]
entries.append((REF,'English reference: LLaMA-3.1-8B','eng',4.275,-17.25,'black!65'))
for model,name,aligned,x,y,color in entries:
 g=group(model)
 if model==REF:
  lines += [r'\draw[black!25] (-.5,-16.1) -- (16,-16.1);']
 coords=' '.join(f"({i},{float(r['mean_score']):.6f})" for i,r in enumerate(g))
 bars=' '.join(f"({i},{float(r['mean_score']):.6f}) += (0,{float(r['mean_ci_high'])-float(r['mean_score']):.6f}) -= (0,{float(r['mean_score'])-float(r['mean_ci_low']):.6f})" for i,r in enumerate(g))
 lines += [rf'\begin{{axis}}[srprofile,at={{({x}cm,{y}cm)}},anchor=north west,title={{{name}}},xticklabels={{{labels(g,aligned)}}}]',r'\path[fill=black!7] (axis cs:-.35,0) rectangle (axis cs:.35,1);',rf'\addplot[color={color},mark=*,mark size=1.6pt,line width=.75pt] coordinates {{{coords}}};',rf'\addplot[color={color},opacity=.65,only marks,mark=none,error bars/.cd,y dir=both,y explicit] coordinates {{{bars}}};',r'\end{axis}']
lines.append(r'\end{tikzpicture}')
(FIGURES/'strongreject_profiles.tex').write_text('% Generated by eval/scripts/write_reference_comparison_figures.py.\n'+'\n'.join(lines)+'\n')

# Regenerate the original BELEBELE panels into a new release, then compact their
# vertical spacing and add the reference's IF/CONS and SPEC side by side.
m=runpy.run_path(str(Path(__file__).with_name('write_belebele_profiles.py')))
f=m['main']
f.__globals__['RELEASE']=RELEASE/'paired-belebele-base'
f()
text=(FIGURES/'belebele_profiles.tex').read_text()
# Axis placements are computed by the original generator, not rounded from pixels.
def compact(match):
 x,y=float(match[1]),float(match[2]); row=round(abs(y)/5.65)
 is_spec=abs(abs(y)-row*5.65)>1
 # Determine row correctly for SPEC coordinates.
 if is_spec: row=round((abs(y)-2.45)/5.65)
 new_y=-row*4.95-(2.05 if is_spec else 0)
 return f'at={{({x:.2f}cm,{new_y:.2f}cm)}}'
text=re.sub(r'at=\{\(([-\d.]+)cm,([-\d.]+)cm\)\}',compact,text)
text=text.replace('height=2.2cm','height=1.8cm').replace('height=1.5cm','height=1.25cm')
g=group(REF); cov={(r['model'],r['attack_language']):r for r in coverage}
ref=[cov[REF,r['attack_language']] for r in g]
assert all(int(r['n_cons_comparable'])>=100 for r in ref)
extra=[r'\draw[black!25] (-.5,-19.55) -- (16,-19.55);',r'\node[anchor=south,font=\small\bfseries] at (7.8,-20.2) {English reference: LLaMA-3.1-8B (descriptive)};']
for col,metric in enumerate(['if_score','spec_score']):
 options=(r'ymin=-.03,ymax=1.06,ytick={0,.2,.4,.6,.8,1},ylabel={IF / CONS}' if col==0 else r'ymin=-2.65,ymax=2.15,ytick={-2,0,2},ylabel={SPEC}')
 extra += [rf'\begin{{axis}}[belebeleaxis,height=1.8cm,at={{({8.55*col}cm,-20.8cm)}},anchor=north west,{options},xticklabels={{{labels(g,"eng")}}},x tick label style={{rotate=55,anchor=east,font=\scriptsize}}]',r'\path[fill=black!7] (axis cs:-.35,'+('-.03' if col==0 else '-2.65')+') rectangle (axis cs:.35,'+('1.06' if col==0 else '2.15')+');']
 for field,color in ([('if_score','belebeleif'),('cons_score','belebelecons')] if col==0 else [('spec_score','belebelespec')]):
  coords=' '.join(f"({i},{float(r[field]):.6f})" for i,r in enumerate(ref))
  extra.append(rf'\addplot[color={color},mark=*,mark size=1.5pt,line width=.75pt] coordinates {{{coords}}};')
 if col==0:
  bars=' '.join(f"({i},{float(r['cons_score']):.6f}) += (0,{float(r['cons_ci_high'])-float(r['cons_score']):.6f}) -= (0,{float(r['cons_score'])-float(r['cons_ci_low']):.6f})" for i,r in enumerate(ref))
  extra.append(rf'\addplot[color=belebelecons,opacity=.45,only marks,mark=none,error bars/.cd,y dir=both,y explicit] coordinates {{{bars}}};')
 else: extra.append(r'\addplot[black!45,dashed,mark=none] coordinates {(-.4,0) (12.4,0)};')
 extra.append(r'\end{axis}')
text=text.replace(r'\end{tikzpicture}','\n'.join(extra)+'\n'+r'\end{tikzpicture}')
(FIGURES/'belebele_profiles.tex').write_text('% Reference extension by eval/scripts/write_reference_comparison_figures.py.\n'+text)

# SPEC scatter, rendered natively with PGFPlots like the profile figures.
lines=[r'\definecolor{srweak}{RGB}{35,103,159}',r'\definecolor{srstrong}{RGB}{202,86,42}',r'\begin{tikzpicture}',
 r'\pgfplotsset{srscatter/.style={width=7.05cm,height=2.65cm,scale only axis,ymin=0,ymax=1,ytick={0,.2,.4,.6,.8,1},xlabel={SPEC},ylabel={Mean score},axis lines=box,grid=major,grid style={black!12},tick label style={font=\scriptsize},label style={font=\footnotesize},title style={font=\bfseries\small},enlarge x limits=.15}}']
for model,name,aligned,x,y,color in entries:
 y = -19.4 if model == REF else y * (4.7 / 4.15)
 g=group(model)
 if model==REF:lines.append(r'\draw[black!25] (-.5,-18.2) -- (16,-18.2);')
 coords=' '.join(f"({float(r['spec_score']):.6f},{float(r['mean_score']):.6f})" for r in g)
 lines += [rf'\begin{{axis}}[srscatter,at={{({x}cm,{y}cm)}},anchor=north west,title={{{name}}}]',rf'\addplot[only marks,color={color},mark=*,mark size=1.7pt] coordinates {{{coords}}};']
 minimum = min(float(r['mean_score']) for r in g)
 maximum = max(float(r['mean_score']) for r in g)
 chosen = [r for r in g if r['attack_language'] == aligned or float(r['mean_score']) in {minimum,maximum}]
 for index,r in enumerate(chosen):
  value=float(r['mean_score']);v=float(r['spec_score'])
  roles=[]
  if r['attack_language']==aligned:roles.append('aligned')
  if value==minimum:roles.append('min')
  if value==maximum:roles.append('max')
  if 'aligned' in roles: position,anchor = '.96,.55','east'
  elif 'max' in roles: position,anchor = '.04,.87','west'
  else: position,anchor = '.04,.25','west'
  label = r['attack_language']+' ('+', '.join(roles)+')'
  identifier='annotation'+str(index)
  lines.append(rf'\node[font=\scriptsize,anchor={anchor},fill=white,fill opacity=.92,text opacity=1,inner sep=1.5pt] ({identifier}) at (rel axis cs:{position}) {{{label}}};')
  lines.append(rf'\draw[black!45,line width=.35pt] ({identifier}.south) -- (axis cs:{v:.6f},{value:.6f});')
  lines.append(rf'\addplot[only marks,color={color},mark=o,mark size=2.5pt,line width=.5pt] coordinates {{({v:.6f},{value:.6f})}};')
 lines.append(r'\end{axis}')
lines.append(r'\end{tikzpicture}')
(FIGURES/'graded_spec_reference_scatter.tex').write_text('% Generated by eval/scripts/write_reference_comparison_figures.py.\n'+'\n'.join(lines)+'\n')
outputs=[FIGURES/n for n in ['strongreject_profiles.tex','belebele_profiles.tex','graded_spec_reference_scatter.tex']]
for p in outputs:shutil.copy2(p,RELEASE/p.name)
for p in [Path(__file__),Path(__file__).with_name('write_belebele_profiles.py')]:shutil.copy2(p,RELEASE/p.name)
manifest={'analysis_rerun':False,'reference_role':'Separate descriptive baseline; not a fifth weak/strong pair and not added to paired inference.','spec_standardization':'Saved all-117-cell standardization unchanged.','checksums':{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in [CELLS,COVERAGE,*outputs,Path(__file__),Path(__file__).with_name('write_belebele_profiles.py')]}}
(RELEASE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
