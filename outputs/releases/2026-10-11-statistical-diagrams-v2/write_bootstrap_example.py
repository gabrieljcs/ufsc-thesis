"""Generate a pedagogical resample from immutable StrongREJECT observations."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'eval/outputs/releases/2026-09-09-corrected/dataset_corrected.jsonl'
OUT = ROOT / 'ufscthesisx/ufscthesisx/chapters/bootstrap_example.tex'
PROMPTS = ['strongreject_0001', 'strongreject_0002', 'strongreject_0003']
LANGS = ['por', 'eng']
scores = {}
with SOURCE.open() as handle:
    for line in handle:
        row = json.loads(line)
        if (row['model'] == 'sagui_7b' and row['prompt_id'] in PROMPTS
                and row['attack_language'] in LANGS and not row['excluded']
                and row['strongreject_score'] is not None):
            key = (row['prompt_id'], row['attack_language'])
            assert key not in scores
            scores[key] = float(row['strongreject_score'])
assert len(scores) == 6
original = [scores[(p, lang)] for p in PROMPTS for lang in LANGS]
resample = [PROMPTS[0], PROMPTS[0], PROMPTS[2]]
selected = [scores[(p, lang)] for p in resample for lang in LANGS]
pairs = [f"({scores[(p, 'por')]:.3f}, {scores[(p, 'eng')]:.3f})" for p in PROMPTS]
text = (
    r'\paragraph*{A small example with actual scores.} '
    'To make the calculation concrete, consider Sagui-7B responses to just three source prompts, 0001, 0002, and 0003, '
    'in Portuguese and English. Their observed score pairs (Portuguese, English) are '
    + ', '.join(pairs[:-1]) + ', and ' + pairs[-1] + ', respectively. '
    + f'Adding all six scores and dividing by six gives the original mean, ${sum(original):.3f}/6 = {sum(original)/6:.4f}$.\n\n'
    'Now imagine three prompt cards in a bag, labelled 0001, 0002, and 0003. '
    'We draw one card, record its identifier, and put it back before drawing again. '
    'After three draws, we might have 0001, 0001, and 0003. '
    'We build a new sample from the responses belonging to those cards: '
    'the Portuguese and English scores for 0001 appear twice, those for 0003 appear once, and those for 0002 do not appear. '
    + f'This new sample still has six scores, but its mean is ${sum(selected):.3f}/6 \\approx {sum(selected)/6:.4f}$. '
    'It is higher because the draw included the higher-scoring prompt 0001 twice and omitted prompt 0002. '
    'Another draw could include prompt 0002 twice and give a lower mean. '
    'The scores in this example are real; the card selections illustrate the procedure and are not reported analysis replicates.\n'
)

OUT.write_text('% Generated by eval/scripts/write_bootstrap_example.py.\n' + text)

# Native TikZ diagram combines an illustrative draw with a saved full-model result.
import csv
SUMMARY = ROOT / 'eval/outputs/releases/2026-09-29-graded-reporting/model_summary.csv'
saved = next(r for r in csv.DictReader(SUMMARY.open())
             if r['model'] == 'sagui_7b' and r['scope'] == 'all_languages')
mean, low, high = [float(saved[k]) for k in ['mean_score', 'mean_ci_low', 'mean_ci_high']]
FIGURE = ROOT / 'ufscthesisx/ufscthesisx/figures/bootstrap_worked_example.tex'
lines = [
    '% Generated by eval/scripts/write_bootstrap_example.py; saved estimates unchanged.',
    r'\begin{figure}[p]\centering',
    r'\begin{tikzpicture}[x=1cm,y=1cm,font=\fontsize{10}{12}\selectfont,',
    r'card/.style={draw=black!20,rounded corners=3pt,text width=3.15cm,minimum height=1.25cm,align=left,inner sep=7pt},',
    r'flow/.style={-{Latex[length=2mm]},thick,draw=black!40}]',
    r'\definecolor{bootblue}{HTML}{286F8C}',
    r'\definecolor{bootorange}{HTML}{A64B39}',
    r'\node[anchor=west,font=\bfseries] at (0,0) {A. One draw, using three real prompt groups};',
    r'\node[anchor=west] at (0,-.55) {Saved scores (por, eng)};',
    r'\node[anchor=west] at (5,-.55) {Selected groups (por, eng)};',
    r'\node[anchor=west] at (10,-.55) {Recalculate};',
]
for i, prompt in enumerate(PROMPTS):
    lines.append(r'\node[card,fill=bootblue!5,anchor=north west] (o'+str(i)+') at (0,'+str(-.9-i*1.6)+') {\\textbf{Prompt '+prompt[-4:]+r'}\\('+f"{scores[(prompt,'por')]:.3f}"+', '+f"{scores[(prompt,'eng')]:.3f}"+')};')
for i, prompt in enumerate(resample):
    fill = 'bootorange!8' if i < 2 else 'bootblue!5'
    lines.append(r'\node[card,fill='+fill+r',anchor=north west] (s'+str(i)+') at (5,'+str(-.9-i*1.6)+') {\\textbf{Prompt '+prompt[-4:]+r'}\\('+f"{scores[(prompt,'por')]:.3f}"+', '+f"{scores[(prompt,'eng')]:.3f}"+')};')
lines += [
    r'\draw[flow] (o0.east) -- (s0.west);',
    r'\draw[flow,draw=bootorange] (o0.east) -- (s1.west);',
    r'\draw[flow] (o2.east) -- (s2.west);',
    r'\node[anchor=north west,text width=3.8cm,align=left] at (10,-1.05) {\textbf{Original mean}\\[5pt]$'+f'{sum(original):.3f}/6 = {sum(original)/6:.4f}'+r'$\\[18pt]\textbf{Resampled mean}\\[5pt]$'+f'{sum(selected):.3f}/6 \\approx {sum(selected)/6:.4f}'+r'$};',
    r'\draw[flow] (8.7,-2.9) -- (9.8,-2.9);',
    r'\node[anchor=north west,text width=14cm,align=left] at (0,-5.6) {\textbf{What changed?} Prompt 0001 was selected twice; 0002 was omitted. Both language scores travel together. The saved scores never change.};',
    r'\draw[black!25] (0,-6.8) -- (14,-6.8);',
    r'\node[anchor=west,font=\bfseries] at (0,-7.3) {B. Repeat on the full scored subset};',
    r'\node[anchor=north west,text width=14cm,align=left] at (0,-7.7) {Each draw selects as many groups as the original subset contains, with replacement. Copy their responses and calculate one mean. Repeat with fresh draws 2,000 times.};',
    r'\node[draw=bootblue!40,fill=bootblue!5,rounded corners=3pt,anchor=north west,text width=13.5cm,align=center,inner sep=8pt] at (0,-9.1) {Draw groups $\longrightarrow$ copy saved responses $\longrightarrow$ one mean\\[5pt]$\mu^{(1)},\ \mu^{(2)},\ \ldots,\ \mu^{(2000)}$};',
    r'\node[anchor=north west,text width=14cm,align=left] at (0,-10.8) {Order the 2,000 means. Their 2.5th and 97.5th percentiles give the lower and upper interval endpoints. The reported point estimate is still the original mean.};',
    r'\draw[black!25] (0,-12.0) -- (14,-12.0);',
    r'\node[anchor=west,font=\bfseries] at (0,-12.5) {C. An actual reported result: Sagui-7B, all 13 languages};',
    r'\node[anchor=north west,text width=14cm,align=left] at (0,-12.9) {'+f"{int(saved['n']):,} scored responses from {int(saved['n_prompts'])} source-prompt groups. Saved mean: {mean:.3f}; saved 95\\% interval: [{low:.3f}, {high:.3f}]."+'};',
    r'\begin{axis}[at={(.7cm,-14.35cm)},anchor=north west,width=12.6cm,height=1.3cm,scale only axis,',
    r'xmin=.35,xmax=.44,ymin=0,ymax=1,axis y line=none,axis x line=bottom,clip=false,',
    r'xtick={.35,.38,.41,.44},tick label style={font=\scriptsize},xlabel={Mean StrongREJECT score (detail of the score scale)},label style={font=\scriptsize}]',
    r'\addplot[bootblue,very thick,mark=|,mark size=5pt] coordinates {('+f'{low:.6f},.5) ({high:.6f},.5)'+'};',
    r'\addplot[bootblue,only marks,mark=*,mark size=3pt] coordinates {('+f'{mean:.6f},.5)'+'};',
    r'\node[anchor=south,font=\scriptsize] at (axis cs:'+f'{mean:.6f},.7)'+' {Original mean};',
    r'\end{axis}',
    r'\node[anchor=north west,text width=14cm,align=left,font=\fontsize{9}{11}\selectfont] at (0,-16.7) {The interval describes variation under resampling of the observed prompts. It does not correct missing scores or judge errors. No new model answers are generated.};',
    r'\end{tikzpicture}',
    r'\caption[How the prompt-cluster bootstrap works]{From a prompt-group draw to a reported interval. Panel A uses actual scores with an illustrative selection; panel B explains the full procedure. Panel C displays the saved full-model result, not an interval calculated from the three-prompt example.}',
    r'\label{fig:bootstrap-worked-example}\fonte{Author; frozen scores and saved graded summary.}',
    r'\end{figure}',
]
FIGURE.write_text('\n'.join(lines)+'\n')
